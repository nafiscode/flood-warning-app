"""Report and seed for the coastal gate."""

from __future__ import annotations

import csv
import json

import pandas as pd

SEED_NAME = "49_coastal_gate.sql"
SEASON_MONTHS = (10, 11, 12, 1)


def windows_from_timeline(path, zone: str) -> dict[str, tuple[str, str]]:
    """Each season's flood window for one zone, from pipeline/data/event_timeline.csv: the earliest
    onset and the latest recession across that zone's districts."""
    with open(path, encoding="utf-8") as f:
        rows = [r for r in csv.DictReader(f) if r["zone"] == zone]
    out: dict[str, tuple[str, str]] = {}
    for event in sorted({r["event"] for r in rows}):
        part = [r for r in rows if r["event"] == event]
        starts = [r["flood_onset"][:10] for r in part if r["flood_onset"]]
        ends = [r["receded"][:10] for r in part if r["receded"]]
        peaks = [r["peak"][:10] for r in part if r["peak"]]
        # A district row may carry only an onset, only a peak or only a recession, so the window is
        # the earliest and the latest date of any kind that the zone's rows give.
        known = starts + peaks + ends
        if not known:
            continue
        out[event] = (min(starts) if starts else min(known), max(ends) if ends else max(known))
    return out


def window_figures(days: pd.DataFrame, ref: dict, a: str, b: str) -> dict | None:
    """What the sea did over one window, and where that sits among the mouth's season days."""
    w = days.loc[a:b]
    if w.empty:
        return None
    season = days[days.index.month.isin(SEASON_MONTHS)]

    def pct(col: str, v: float):
        return None if season.empty else round(100.0 * float((season[col] < v).mean()))

    return {
        "from": a, "to": b, "days": int(len(w)),
        "llw_max": round(float(w["llw"].max()), 2), "llw_pct": pct("llw", w["llw"].max()),
        "hhw_max": round(float(w["hhw"].max()), 2), "hhw_pct": pct("hhw", w["hhw"].max()),
        "setup_max": round(float(w["setup"].max()), 2), "setup_pct": pct("setup", w["setup"].max()),
        "range_min": round(float(w["range"].min()), 2),
        "shut_days": int((w["llw"] >= ref["llw_p90"]).sum()) if "llw_p90" in ref else None,
    }


def markdown(mouths: list[dict], cfg: dict, made: str) -> str:
    ref0 = cfg["reference"]
    months = ", ".join(str(m) for m in ref0["months"])
    flag = cfg["flag"]
    out = [
        "# The coastal gate: the low-water window at each river mouth",
        "",
        "Generated by `uv run python -m coastal_gate run`, " + made + ". Method: `METHODS.md`;",
        "science plan Module 10. Advisory only: nothing here publishes an alert and nothing here can",
        "raise a level (safety rule 2).",
        "",
        "A river drains while the sea is below it, so what keeps water in after the rain stops is not",
        "the high tide but the **low** tide, the floor the river has to get over. Monsoon set-up lifts",
        "that floor; when the tidal range collapses at the same time, the floor never drops and the",
        "water stays for days.",
        "",
        "Reference months: " + months + ". Percentiles are over those months of the whole archive",
        "(" + cfg["archive"]["first"] + " to " + cfg["archive"]["last"] + "). Open-Meteo's marine",
        "archive of sea_level_height_msl begins in late 2022, so that is the whole record, not a choice.",
        "",
        "## The reference at each mouth",
        "",
        "| Mouth | Zone | Grid cell | Season days | Low water p50 / p90 / p98 (m) | Set-up p50 / p90 / p98 (m) | Mean range (m) |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in mouths:
        r, g = m["reference"], m["grid"]
        out.append(
            "| %s | %s | %.3f N, %.3f E | %d | %.2f / %.2f / %.2f | %.2f / %.2f / %.2f | %.2f |"
            % (m["name"]["en"], m["zone"] or "**none**", g[1], g[0], r["days"],
               r["llw_p50"], r["llw_p90"], r["llw_p98"],
               r["setup_p50"], r["setup_p90"], r["setup_p98"], r["range_mean"]))

    out += ["", "## The floods on record", "",
            "Windows from `pipeline/data/event_timeline.csv`, the curated flood timeline: the earliest",
            "onset to the latest recession across the zone's districts. A percentile of 96 means the sea",
            "stood higher than 96% of that mouth's flood-season days.", ""]
    for m in mouths:
        head = "### " + m["name"]["en"]
        if m.get("windows_from"):
            head += " (windows borrowed from " + m["windows_from"] + ")"
        out += [head, ""]
        if not m["events"]:
            out += ["No window on record.", ""]
            continue
        out += ["| Event | Window | Low water max (pct) | High water max (pct) | Set-up max (pct) | Smallest range | Shut days |",
                "|---|---|---|---|---|---|---|"]
        for name, e in m["events"].items():
            out.append("| %s | %s to %s | **%.2f (%s)** | %.2f (%s) | %.2f (%s) | %.2f | %s |"
                       % (name, e["from"], e["to"], e["llw_max"], e["llw_pct"], e["hhw_max"],
                          e["hhw_pct"], e["setup_max"], e["setup_pct"], e["range_min"], e["shut_days"]))
        out.append("")

    out += ["## Spells with no low-water window", "",
            "Runs of at least %d days whose lowest sea level stayed at or over the mouth's low-water"
            % flag["shut_days"],
            "p%d. This is the base rate behind the live flag: how often an admin would see it, and"
            % flag["shut_percentile"],
            "whether the floods on record are among them.", ""]
    for m in mouths:
        season = [s for s in m["spells"]
                  if int(s["from"][5:7]) in ref0["months"] or int(s["to"][5:7]) in ref0["months"]]
        out += ["**%s**: %d spells in the archive, %d in the season months."
                % (m["name"]["en"], len(m["spells"]), len(season)), ""]
        for s in season:
            out.append("- %s to %s (%d d, low water up to %.2f m, set-up %.2f m)"
                       % (s["from"], s["to"], s["days"], s["llw_max"], s["setup_max"]))
        out.append("")

    out += ["## Does the wind see it coming?", "",
            "Onshore wind stress (ERA5 at the same point, the onshore component squared, the shoreline",
            "taken as north-west to south-east so onshore is from 045) against the set-up, both",
            "Godin-filtered. A positive lag means the wind leads.", "",
            "| Mouth | Season hours | r all year | r in season | r by wind lead (0 / 12 / 24 / 36 / 48 h) |",
            "|---|---|---|---|---|"]
    for m in mouths:
        w = m.get("wind") or {}
        if "r_season" not in w:
            out.append("| %s | %d | - | - | not enough hours |" % (m["name"]["en"], w.get("hours", 0)))
            continue
        lags = " / ".join("%+.2f" % v for v in w["r_by_lag_h"].values())
        out.append("| %s | %d | %+.2f | %+.2f | %s |"
                   % (m["name"]["en"], w["hours"], w["r_all_year"], w["r_season"], lags))

    out += ["", "## What this is not", "",
            "- **Not a gauge.** Open-Meteo's modelled sea level sat about 0.7 m off the Pattani tide",
            "  gauge (A8, 14 Oct 2026), and the model's cell is a few kilometres offshore of each mouth.",
            "  Read the percentiles and the anomalies, never the absolute metres.",
            "- **Not many seasons.** The archive holds three Novembers and four Decembers. A percentile",
            "  from that is a first estimate, and the live flag is worth re-cutting after this season.",
            "- **Not a trigger.** The sea floods nothing on its own. It says how long the water stays, so",
            "  it is a modifier beside the rain and the gauges, and it tells the safe-return window which",
            "  end of its range to expect.",
            "- **Not checked against a local gauge.** ThaiWater lists station 2143 `NR` at the Bang Nara",
            "  mouth but answers no readings for 2024-2026, so there is no observed tide here to test.",
            ""]
    return "\n".join(out) + "\n"


def seed_sql(mouths: list[dict], cfg: dict, made: str) -> str:
    def num(v):
        return "null::double precision" if v is None else repr(float(v)) + "::double precision"

    out = [
        "-- Generated by `uv run python -m coastal_gate run` (pipeline/coastal_gate). Do not edit by hand.",
        "-- The coastal gate (science plan Module 10): what the sea's low water and monsoon set-up normally",
        "-- do at each river mouth in the flood season, so the live marine forecast can be read against it.",
        "-- Advisory only; it can never raise an alert level (safety rule 2).",
        "insert into public.coastal_gate_reference (id, zone_id, name, lat, lon, llw_p50, llw_p90, llw_p98,",
        "  setup_p50, setup_p90, setup_p98, season_days, method)",
        "select v.id, z.id, v.name::jsonb, v.lat, v.lon, v.llw_p50, v.llw_p90, v.llw_p98,",
        "  v.setup_p50, v.setup_p90, v.setup_p98, v.season_days, v.method::jsonb",
        "from (values",
    ]
    values = []
    for m in mouths:
        r = m["reference"]
        method = {
            "source": "coastal_gate run, " + made,
            "model": "open-meteo marine sea_level_height_msl",
            "requested_point": m["point"], "grid_point": m["grid"],
            "archive": cfg["archive"], "filter": cfg["filter"], "reference": cfg["reference"],
            "flag": cfg["flag"],
            "percentiles": {k: v for k, v in r.items() if k != "days"},
            "monthly": m["months"], "events": m["events"], "spells": m["spells"],
            "wind": m.get("wind"), "windows_from": m.get("windows_from"),
            "caveats": ["model, not a gauge: about 0.7 m off the Pattani tide gauge (A8)",
                        "grid cell is a few kilometres offshore of the mouth",
                        "three Novembers and four Decembers in the archive",
                        "advisory: never raises a level, only says how long the water stays"],
        }
        text = json.dumps(method, ensure_ascii=False).replace("'", "''")
        name = json.dumps(m["name"], ensure_ascii=False).replace("'", "''")
        basin = "null" if m["zone"] is None else "'" + m["zone"] + "'"
        values.append(
            "  ('%s', %s, '%s', %s, %s, %s, %s, %s, %s, %s, %s, %d, '%s')"
            % (m["id"], basin, name, num(m["grid"][1]), num(m["grid"][0]),
               num(r["llw_p50"]), num(r["llw_p90"]), num(r["llw_p98"]),
               num(r["setup_p50"]), num(r["setup_p90"]), num(r["setup_p98"]),
               int(r["days"]), text))
    out.append(",\n".join(values))
    out += [
        ") as v (id, basin, name, lat, lon, llw_p50, llw_p90, llw_p98, setup_p50, setup_p90, setup_p98,",
        "        season_days, method)",
        "left join public.warning_zones z on z.basin = v.basin",
        "on conflict (id) do update",
        "  set zone_id = excluded.zone_id, name = excluded.name, lat = excluded.lat, lon = excluded.lon,",
        "      llw_p50 = excluded.llw_p50, llw_p90 = excluded.llw_p90, llw_p98 = excluded.llw_p98,",
        "      setup_p50 = excluded.setup_p50, setup_p90 = excluded.setup_p90,",
        "      setup_p98 = excluded.setup_p98, season_days = excluded.season_days,",
        "      method = excluded.method, updated_at = now();",
    ]
    return "\n".join(out) + "\n"
