"""Reading the gauges' levels as loaded (seed 47) and writing the events, the report and seed 48."""

from __future__ import annotations

import json
import re

ROW = re.compile(
    r"^\s*\((\d+),\s*(null|-?[\d.]+)::double precision,\s*(null|-?[\d.]+)::double precision,\s*"
    r"(null|-?[\d.]+)::double precision,\s*'(.*)'\),?\s*$")


def read_levels(sql: str) -> dict[int, dict]:
    """{thaiwater_id: {"watch", "warning", "evacuate", "method"}} from 47_gauge_levels.sql."""
    out = {}
    for line in sql.splitlines():
        m = ROW.match(line)
        if not m:
            continue

        def num(s: str) -> float | None:
            return None if s == "null" else float(s)
        out[int(m.group(1))] = {"watch": num(m.group(2)), "warning": num(m.group(3)), "evacuate": num(m.group(4)),
                                "method": json.loads(m.group(5).replace("''", "'"))}
    return out


def zone_roles(zones: dict) -> dict[int, tuple[str, str]]:
    """{thaiwater_id: (zone, role)} from the thresholds config's zones."""
    out = {}
    for zone, z in zones.items():
        for role, items in (("key", [z["key"]]), ("upstream", [z["upstream"]]),
                            ("downstream", z.get("downstream", [])), ("other", z.get("extra", []))):
            for g in items:
                out[int(g["id"])] = (zone, role)
    return out


EVENT_COLUMNS = ["code", "thaiwater_id", "zone", "season", "start_utc", "peak_utc", "peak_bangkok", "peak_m",
                 "warning_m", "bank_m", "over_bank", "hours_above_warning", "to_bank_h", "to_bank_censored",
                 "to_warning_h", "to_warning_censored", "above_bank_h", "dropped"]


def event_row(g: dict, e: dict) -> dict:
    return {
        "code": g["code"], "thaiwater_id": g["thaiwater_id"], "zone": g.get("zone") or "",
        "season": e["season"], "start_utc": e["start"].isoformat(), "peak_utc": e["peak_at"].isoformat(),
        "peak_bangkok": e["peak_at"].tz_convert("Asia/Bangkok").strftime("%Y-%m-%d %H:%M"),
        "peak_m": e["peak_m"], "warning_m": g["warning"], "bank_m": g["bank"], "over_bank": e["over_bank"],
        "hours_above_warning": e["hours_above_warning"],
        "to_bank_h": "" if e["to_bank_h"] is None else e["to_bank_h"], "to_bank_censored": e["to_bank_censored"],
        "to_warning_h": "" if e["to_warning_h"] is None else e["to_warning_h"],
        "to_warning_censored": e["to_warning_censored"],
        "above_bank_h": "" if e["above_bank_h"] is None else e["above_bank_h"], "dropped": e["dropped"] or "",
    }


ZONE_ORDER = {"pattani_river": 0, "kolok": 1, "u_taphao": 2}
ROLE_ORDER = {"key": 0, "upstream": 1, "downstream": 2, "other": 3}


def order(g: dict) -> tuple:
    return (ZONE_ORDER.get(g.get("zone"), 9), ROLE_ORDER.get(g.get("role"), 9), g["code"])


def _q(q: dict) -> str:
    if not q or q["n"] == 0:
        return "–"
    if q["p50"] is None:
        if q["min"] == q["max"]:
            return f"{q['min']:g} h (n={q['n']})"
        return f"{q['min']:g}–{q['max']:g} h (n={q['n']})"
    return f"{q['p50']:g} h ({q['p25']:g}–{q['p75']:g}; {q['min']:g}–{q['max']:g})"


def _flags(g: dict) -> str:
    out = []
    if g["flags"].get("tidal"):
        out.append("tidal")
    if g["flags"].get("lake"):
        out.append("Songkhla Lake")
    if g["flags"].get("coastal_unchecked"):
        out.append("near a mouth, tide not checked")
    if g["flags"].get("bank_suspect"):
        out.append("**bank looks too low**")
    if g["flags"].get("never_reached_bank"):
        out.append("never over its bank")
    if g["summary"]["few_events"]:
        out.append("too few events")
    return ", ".join(out)


def markdown(gauges: list[dict], cfg: dict, made: str) -> str:
    ev, sm = cfg["events"], cfg["summary"]
    lines = [
        "# Safe-return window: how long each river took to fall back",
        "",
        f"Generated by `uv run python -m safe_return run` on {made} from the hourly ThaiWater archive",
        "(science plan Module 5; method in METHODS.md beside this file). For the admins who write a Return",
        "alert's window: the record of past falls, not a forecast of this one.",
        "",
        f"An **event** is the gauge at or above its Warning level for at least {ev['min_hours']} hours in a row;",
        f"spells closer than {ev['stay_below_h']} hours are one event. **Below** means below the level and staying",
        f"below for {ev['stay_below_h']} observed hours. Durations run from the event's highest reading. Each cell:",
        "median (25th–75th percentile; shortest–longest), over the events with a complete fall; a censored",
        "event (a gap or the end of the record before the fall) is counted apart and left out of the figures.",
        f"Under {sm['min_events']} complete events no median or range is given.",
        "",
    ]
    for zone in list(ZONE_ORDER) + [None]:
        rows = [g for g in gauges if g.get("zone") == zone]
        if not rows:
            continue
        title = {"pattani_river": "Pattani River", "kolok": "Kolok River", "u_taphao": "Khlong U-Taphao"}.get(zone, "Other gauges")
        lines += [f"## {title}", "",
                  "| Gauge | Role | Warning / bank (m) | Events (over bank) | Peak to below bank | Typical | Peak to below Warning, all events | Typical | Below Warning, over-bank floods | Hours over bank | Censored | Seasons | Notes |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for g in sorted(rows, key=order):
            s = g["summary"]
            seasons = "–" if s["first_season"] is None else f"{s['first_season']}–{s['last_season']}"
            rb = (s["to_bank_range"] or {}).get("text", "–")
            rw = (s["to_warning_range"] or {}).get("text", "–")
            drop = sum(s["dropped"].values())
            cens = f"{s['censored']}" + (f" (+{drop} dropped)" if drop else "")
            lines.append(
                f"| {g['code']} | {g.get('role') or '–'} | {g['warning']:.2f} / {g['bank']:.2f} | {s['events']} ({s['over_bank']}) | "
                f"{_q(s['to_bank_h'])} | {rb} | {_q(s['to_warning_h'])} | {rw} | {_q(s['to_warning_h_over_bank'])} | {_q(s['above_bank_h'])} | "
                f"{cens} | {seasons} | {_flags(g)} |")
        lines.append("")
    lines += [
        "## Reading it",
        "",
        "- Tidal gauges fall below a line at every low tide; staying below for twelve hours needs the high tide",
        "  below it too, so the figure there is how long until the high tides themselves were clear.",
        "- Songkhla Lake gauges fall with the lake, which drains slowly through one outlet: their times are",
        "  the lake's, and wind can hold the water up for days.",
        "- A gauge whose listed bank looks too low (the river within 0.3 m of it for over a tenth of the record)",
        "  has events that are mostly ordinary high water: do not use its figures.",
        "- Rain on a falling river starts it rising again: an event with a second peak counts the whole of it.",
        "- \"Below Warning, over-bank floods\" is the figure to read after an Evacuate; \"all events\" mixes in",
        "  Warning-only events, whose short falls can put it under the time to the bank.",
        f"- Only events peaking in months {', '.join(str(m) for m in ev.get('months') or [])} count; the others are listed",
        "  in events.csv as `off_season`. Excluded periods (`excluded`):",
    ]
    for x in cfg.get("exclude") or []:
        lines.append(f"  - {x['code']}, {x['from']} to {x['to']}: {x['why']}")
    lines += [
        "",
    ]
    return "\n".join(lines)


def seed_sql(gauges: list[dict], cfg: dict, made: str) -> str:
    """supabase/seed/48_gauge_recession.sql: one row per gauge with levels, matched by ThaiWater id."""
    def num(v):
        return "null::double precision" if v is None else f"{round(float(v), 1)!r}::double precision"

    def integer(v):
        return "null::integer" if v is None else f"{int(v)}::integer"

    ev = cfg["events"]
    out = [
        "-- Generated by `uv run python -m safe_return run` (pipeline/safe_return). Do not edit by hand.",
        "-- How long each river gauge took to fall back after its past floods (science plan Module 5): hours",
        "-- from the peak to below the bank and to below Warning, staying below for "
        f"{ev['stay_below_h']} hours. The record, shown",
        "-- to the admin who writes a Return alert's window; not a forecast. Percentiles over complete events",
        "-- only; null under the minimum number of events (method.min_events).",
        "insert into public.gauge_recession (station_id, events, to_bank_h_p25, to_bank_h_p50, to_bank_h_p75,",
        "  to_warning_h_p25, to_warning_h_p50, to_warning_h_p75, above_bank_h_p50, censored, first_season,",
        "  last_season, method)",
        "select s.id, v.events, v.to_bank_h_p25, v.to_bank_h_p50, v.to_bank_h_p75, v.to_warning_h_p25,",
        "  v.to_warning_h_p50, v.to_warning_h_p75, v.above_bank_h_p50, v.censored, v.first_season, v.last_season,",
        "  v.method::jsonb",
        "from (values",
    ]
    values = []
    for g in sorted(gauges, key=order):
        s = g["summary"]
        qb, qw, qa = s["to_bank_h"], s["to_warning_h"], s["above_bank_h"]
        method = {
            "code": g["code"], "zone": g.get("zone"), "role": g.get("role"),
            "warning_m": g["warning"], "bank_m": g["bank"],
            "rules": {k: ev.get(k) for k in ("min_hours", "stay_below_h", "bridge_h", "peak_guard_h", "max_above_bank_m", "months")},
            "min_events": cfg["summary"]["min_events"],
            "over_bank": s["over_bank"], "censored_bank": s["censored_bank"], "censored_warning": s["censored_warning"],
            "dropped": s["dropped"],
            "to_bank_h": {k: qb[k] for k in ("n", "min", "max")}, "to_warning_h": {k: qw[k] for k in ("n", "min", "max")},
            "to_warning_h_over_bank": {k: s["to_warning_h_over_bank"][k] for k in ("n", "p25", "p50", "p75", "min", "max")},
            "above_bank_h": {k: qa[k] for k in ("n", "p25", "p75", "min", "max")},
            "to_bank_range_h": None if not s["to_bank_range"] else [s["to_bank_range"]["low_h"], s["to_bank_range"]["high_h"]],
            "to_warning_range_h": None if not s["to_warning_range"] else [s["to_warning_range"]["low_h"], s["to_warning_range"]["high_h"]],
            "durations": {"to_bank_h": g["durations"]["to_bank_h"], "to_warning_h": g["durations"]["to_warning_h"]},
            "record": g["record"], "flags": g["flags"], "usable": g["usable"],
            "source": f"safe_return run, {made}",
        }
        text = json.dumps(method, ensure_ascii=False).replace("'", "''")
        values.append(
            f"  ({int(g['thaiwater_id'])}, {integer(s['events'])}, {num(qb['p25'])}, {num(qb['p50'])}, {num(qb['p75'])}, "
            f"{num(qw['p25'])}, {num(qw['p50'])}, {num(qw['p75'])}, {num(qa['p50'])}, {integer(s['censored'])}, "
            f"{integer(s['first_season'])}, {integer(s['last_season'])}, '{text}')")
    out.append(",\n".join(values))
    out += [
        ") as v (thaiwater_id, events, to_bank_h_p25, to_bank_h_p50, to_bank_h_p75, to_warning_h_p25,",
        "        to_warning_h_p50, to_warning_h_p75, above_bank_h_p50, censored, first_season, last_season, method)",
        "join public.stations s on s.thaiwater_id = v.thaiwater_id",
        "on conflict (station_id) do update",
        "  set events = excluded.events, to_bank_h_p25 = excluded.to_bank_h_p25, to_bank_h_p50 = excluded.to_bank_h_p50,",
        "      to_bank_h_p75 = excluded.to_bank_h_p75, to_warning_h_p25 = excluded.to_warning_h_p25,",
        "      to_warning_h_p50 = excluded.to_warning_h_p50, to_warning_h_p75 = excluded.to_warning_h_p75,",
        "      above_bank_h_p50 = excluded.above_bank_h_p50, censored = excluded.censored,",
        "      first_season = excluded.first_season, last_season = excluded.last_season, method = excluded.method;",
        "",
    ]
    return "\n".join(out)
