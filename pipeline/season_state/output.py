"""The report and seed 61 for Module 11: the season-state reference per gauge and per zone."""

from __future__ import annotations

import json

from safe_return.output import ROLE_ORDER, ZONE_ORDER, read_levels, zone_roles  # noqa: F401

SEED_NAME = "61_season_state.sql"
MONTH_NAME = {10: "October", 11: "November", 12: "December", 1: "January"}
ZONE_TITLE = {"pattani_river": "Pattani River", "kolok": "Kolok River", "u_taphao": "Khlong U-Taphao"}


def order(g: dict) -> tuple:
    return (ZONE_ORDER.get(g.get("zone"), 9), ROLE_ORDER.get(g.get("role"), 9), g["code"])


def _num(v) -> str:
    return "null::double precision" if v is None else f"{round(float(v), 3)!r}::double precision"


def _int(v) -> str:
    return "null::integer" if v is None else f"{int(v)}::integer"


def _band(ref: dict, digits: int = 2) -> str:
    if ref.get("p33") is None:
        return f"– (seasons {ref.get('seasons', 0)})"
    return " / ".join(f"{float(ref[k]):.{digits}f}" for k in ("p33", "p50", "p67"))


def markdown(gauges: list[dict], zones: list[dict], cfg: dict, made: str, bias: dict | None) -> str:
    ref, rule, tide = cfg["reference"], cfg["rule"], cfg["tide"]
    months = list(ref["months"])
    lines = [
        "# Season state: how wet the catchment already is",
        "",
        f"Generated by `uv run python -m season_state run` on {made} from the local ThaiWater archive and",
        "the cached GSMaP basin rain (science plan Module 11; method in METHODS.md beside this file).",
        "",
        "Two figures, each read only against its own record and never between gauges:",
        "",
        "- **Baseflow**, the gauge's daily *minimum* on Bangkok days - the closest a single gauge comes to a",
        "  tide-free floor. The tide and the day's rain move the maximum about; the floor follows what the",
        "  catchment is holding.",
        "- **Antecedent rain**, the basin-mean rain already fallen over fifteen and thirty days and since the",
        "  first of October.",
        "",
        f"Each cell is the lower third / median / upper third for that month, over at least {ref['min_seasons']} seasons.",
        "A month with fewer seasons gets no figure rather than a figure resting on one year.",
        "",
        "## What the rain had already done, per zone",
        "",
        "| Zone | Basin | Month | 15 days (mm) | 30 days (mm) | Since 1 Oct (mm) | Seasons |",
        "|---|---|---|---|---|---|---|",
    ]
    for z in sorted(zones, key=lambda x: ZONE_ORDER.get(x["zone"], 9)):
        for m in months:
            d15, d30, std = z["d15"][m], z["d30"][m], z["std"][m]
            lines.append(
                f"| {ZONE_TITLE.get(z['zone'], z['zone'])} | {z['basin']} | {MONTH_NAME.get(m, m)} | "
                f"{_band(d15, 0)} | {_band(d30, 0)} | {_band(std, 0)} | {d15.get('seasons', 0)} |")
    lines += [
        "",
        "## The river's floor, per gauge",
        "",
        "A gauge is left out when something other than the catchment moves its floor. A harmonic fit",
        "separates the sea's three periods (M2 12.42 h, K1 23.93 h, O1 25.82 h) from the exactly-24-hour",
        f"line, which is human: the sea above {tide['max_tide_m']} m, or a daily pulse above {tide['max_pulse_m']} m, and the gauge is not",
        "used. The pulse is tested first, because a tall daily pulse leaks into the moon's neighbouring",
        "periods and would otherwise be reported as the sea. Every gauge measured is listed, kept or not.",
        "",
        "| Gauge | Zone | Role | Sea (m) | Daily pulse (m) | Kept | Month | Floor (m) | 7-day change (m) | Seasons |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for g in sorted(gauges, key=order):
        t = g.get("tide") or {}
        share = "–" if t.get("tide_m") is None else f"{t['tide_m']:.3f}"
        amp = "–" if t.get("pulse_m") is None else f"{t['pulse_m']:.3f}"
        kept = "yes" if g["kept"] else f"no ({g['why_dropped']})"
        if not g["kept"]:
            lines.append(f"| {g['code']} | {g.get('zone') or '–'} | {g.get('role') or '–'} | {share} | {amp} | "
                         f"{kept} | – | – | – | {g['record'].get('days', 0)} days |")
            continue
        for m in months:
            lines.append(
                f"| {g['code']} | {g.get('zone') or '–'} | {g.get('role') or '–'} | {share} | {amp} | {kept} | "
                f"{MONTH_NAME.get(m, m)} | {_band(g['floor'][m])} | {_band(g['rise'][m])} | "
                f"{g['floor'][m].get('seasons', 0)} |")
    lines += [
        "",
        "## The soft notice, and how often it would have spoken",
        "",
        f"The rule: the floor rose on at least {rule['rose_days_min']} of the last {rule['rose_window']} days **and** the",
        f"{rule['rain_window_days']}-day basin rain is in the top third of that basin's own record for the month. Both legs, or",
        "nothing is raised. One row per episode, for an admin to look at; it publishes nothing.",
        "",
        "| Zone | Season | Days the rule held | Episodes |",
        "|---|---|---|---|",
    ]
    for z in sorted(zones, key=lambda x: ZONE_ORDER.get(x["zone"], 9)):
        for season, h in sorted((z.get("hindcast") or {}).items()):
            lines.append(f"| {ZONE_TITLE.get(z['zone'], z['zone'])} | {season} | {h['days']} | {h['episodes']} |")
    lines += [
        "",
        "## What this is not",
        "",
        "- **Not a forecast.** Every figure is rain that has already fallen and a river level already read.",
        "- **Not a trigger on its own.** Measured on this archive, the floor at X.40A (Yala) sat about a metre",
        "  *below* its own median for the date through 5-22 November 2025, and the river went over its bank on",
        "  the 24th. The worst flood in the record fell on a catchment that was running low. \"Above normal for",
        "  the date\" is therefore printed beside the grade and is **not** a condition of it.",
        "- **Not comparable between gauges.** A floor of 12 m at one gauge and 2 m at another say nothing about",
        "  each other. Only the position in a gauge's own record travels.",
        f"- **Thin.** The RID key gauges start in February 2020, so six seasons is the most any of them has, and",
        "  the cached basin rain covers 1 October to 31 January only. Terciles, never high percentiles.",
        "",
    ]
    if bias:
        lines += [
            "## GSMaP against Open-Meteo, at the same points",
            "",
            "The terciles above are built from GSMaP; the live figure the dashboard compares against them comes",
            "from Open-Meteo. The two are not the same instrument. Measured over the seasons below, at each",
            "zone's own live rain points, as a ratio of season totals (Open-Meteo / GSMaP):",
            "",
            "| Zone | Season | GSMaP (mm) | Open-Meteo (mm) | Ratio |",
            "|---|---|---|---|---|",
        ]
        for zone, seasons in sorted(bias.get("zones", {}).items()):
            for season, f in sorted(seasons.items()):
                lines.append(f"| {ZONE_TITLE.get(zone, zone)} | {season} | {f['gsmap_mm']:.0f} | "
                             f"{f['open_meteo_mm']:.0f} | {f['ratio']:.2f} |")
        lines += ["", f"Fetched {bias.get('made')}. Open-Meteo attribution: data by Open-Meteo.com.", ""]
    else:
        lines += [
            "## GSMaP against Open-Meteo",
            "",
            "Not measured yet. `uv run python -m season_state bias` asks the Open-Meteo archive for the same",
            "seasons at each zone's own live rain points and writes the comparison here. Until it has run, read",
            "the live fifteen-day figure against these terciles as indicative only: they are different",
            "instruments, and the same mismatch already exists in Module 3's rain thresholds.",
            "",
        ]
    return "\n".join(lines)


def seed_sql(gauges: list[dict], zones: list[dict], cfg: dict, made: str) -> str:
    """supabase/seed/61_season_state.sql: the monthly reference per gauge and per zone."""
    ref, rule = cfg["reference"], cfg["rule"]
    months = list(ref["months"])
    rules = {"min_seasons": ref["min_seasons"], "months": months, "rain_windows": ref["rain_windows"],
             "rule": dict(rule), "tide": dict(cfg["tide"]), "gauge": dict(cfg["gauge"])}
    out = [
        "-- Generated by `uv run python -m season_state run` (pipeline/season_state). Do not edit by hand.",
        "-- Season state (science plan Module 11): how wet each catchment already is, per flood-season month.",
        "-- `season_baseflow` is each kept gauge's daily-minimum floor and its seven-day change; `season_rain`",
        "-- is each zone's basin rain over fifteen days, thirty days and since the first of October. Terciles",
        "-- over whole seasons; null where fewer than method.rules.min_seasons seasons contributed.",
        "-- Advisory only: these figures are read beside an admin's judgement and can never raise a level or",
        "-- publish anything (safety rule 2), and they are a record, not a forecast (safety rule 8).",
        "",
        "insert into public.season_baseflow (station_id, month, floor_p33, floor_p50, floor_p67,",
        "  rise_p33, rise_p50, rise_p67, seasons, days, sea_m, pulse_m, method)",
        "select s.id, v.month, v.floor_p33, v.floor_p50, v.floor_p67, v.rise_p33, v.rise_p50, v.rise_p67,",
        "  v.seasons, v.days, v.sea_m, v.pulse_m, v.method::jsonb",
        "from (values",
    ]
    values = []
    for g in sorted([x for x in gauges if x["kept"]], key=order):
        for m in months:
            f, r = g["floor"][m], g["rise"][m]
            method = {
                "code": g["code"], "zone": g.get("zone"), "role": g.get("role"), "month": m,
                "bank_m": g.get("bank"), "record": g["record"], "tide": g.get("tide"),
                "rules": rules, "source": f"season_state run, {made}",
            }
            text = json.dumps(method, ensure_ascii=False).replace("'", "''")
            values.append(
                f"  ({int(g['thaiwater_id'])}, {m}, {_num(f['p33'])}, {_num(f['p50'])}, {_num(f['p67'])}, "
                f"{_num(r['p33'])}, {_num(r['p50'])}, {_num(r['p67'])}, {_int(f.get('seasons'))}, "
                f"{_int(f.get('days'))}, {_num((g.get('tide') or {}).get('tide_m'))}, "
                f"{_num((g.get('tide') or {}).get('pulse_m'))}, '{text}')")
    out.append(",\n".join(values))
    out += [
        ") as v (thaiwater_id, month, floor_p33, floor_p50, floor_p67, rise_p33, rise_p50, rise_p67,",
        "        seasons, days, sea_m, pulse_m, method)",
        "join public.stations s on s.thaiwater_id = v.thaiwater_id",
        "on conflict (station_id, month) do update",
        "  set floor_p33 = excluded.floor_p33, floor_p50 = excluded.floor_p50, floor_p67 = excluded.floor_p67,",
        "      rise_p33 = excluded.rise_p33, rise_p50 = excluded.rise_p50, rise_p67 = excluded.rise_p67,",
        "      seasons = excluded.seasons, days = excluded.days, sea_m = excluded.sea_m, pulse_m = excluded.pulse_m,",
        "      method = excluded.method, updated_at = now();",
        "",
        "insert into public.season_rain (zone_id, month, d15_p33, d15_p50, d15_p67, d30_p33, d30_p50, d30_p67,",
        "  std_p33, std_p50, std_p67, seasons, days, method)",
        "select z.id, v.month, v.d15_p33, v.d15_p50, v.d15_p67, v.d30_p33, v.d30_p50, v.d30_p67,",
        "  v.std_p33, v.std_p50, v.std_p67, v.seasons, v.days, v.method::jsonb",
        "from (values",
    ]
    values = []
    for z in sorted(zones, key=lambda x: ZONE_ORDER.get(x["zone"], 9)):
        for m in months:
            a, b, c = z["d15"][m], z["d30"][m], z["std"][m]
            method = {
                "zone": z["zone"], "basin": z["basin"], "month": m, "record": z["record"],
                "hindcast": z.get("hindcast"), "rules": rules, "rain_source": "GSMaP v8 operational, gauge-adjusted",
                "source": f"season_state run, {made}",
            }
            text = json.dumps(method, ensure_ascii=False).replace("'", "''")
            values.append(
                f"  ('{z['zone']}', {m}, {_num(a['p33'])}, {_num(a['p50'])}, {_num(a['p67'])}, "
                f"{_num(b['p33'])}, {_num(b['p50'])}, {_num(b['p67'])}, {_num(c['p33'])}, {_num(c['p50'])}, "
                f"{_num(c['p67'])}, {_int(a.get('seasons'))}, {_int(a.get('days'))}, '{text}')")
    out.append(",\n".join(values))
    out += [
        ") as v (basin, month, d15_p33, d15_p50, d15_p67, d30_p33, d30_p50, d30_p67,",
        "        std_p33, std_p50, std_p67, seasons, days, method)",
        "join public.warning_zones z on z.basin = v.basin",
        "on conflict (zone_id, month) do update",
        "  set d15_p33 = excluded.d15_p33, d15_p50 = excluded.d15_p50, d15_p67 = excluded.d15_p67,",
        "      d30_p33 = excluded.d30_p33, d30_p50 = excluded.d30_p50, d30_p67 = excluded.d30_p67,",
        "      std_p33 = excluded.std_p33, std_p50 = excluded.std_p50, std_p67 = excluded.std_p67,",
        "      seasons = excluded.seasons, days = excluded.days, method = excluded.method, updated_at = now();",
        "",
    ]
    return "\n".join(out)
