"""supabase/seed/62_gauge_channel.sql: the channel at each river gauge, for the app's drawing.

Joined to `public.stations` by ThaiWater id, exactly as seed 47 does. A figure that could not be
had is written as null and stays null: the app then draws its own channel and says the shape is a
drawing. Nothing here is a level and nothing here can raise one (safety rule 2).
"""

from __future__ import annotations

import json
from datetime import date


def _num(value) -> str:
    return "null" if value is None else repr(round(float(value), 3))


def _q(text: str | None) -> str:
    return "null" if text is None else "'" + str(text).replace("'", "''") + "'"


def sql(rows: list[dict]) -> str:
    kept = [r for r in rows if r["bed_m"] is not None or r["width_m"] is not None
            or r["left_bank_m"] is not None or r["right_bank_m"] is not None]
    out = [
        "-- Generated by `uv run python -m gauge_section run` (pipeline/gauge_section). Do not edit.",
        "-- The channel at each river gauge, for the cross-section the app draws on a gauge's card:",
        "-- the two bank heights and the bed from ThaiWater's own station record, and the width of",
        "-- the water measured across OpenStreetMap's digitised rivers. A missing figure is null and",
        "-- is drawn as missing. Not a level, not a survey, and nothing here can publish anything.",
        "insert into public.gauge_channel (station_id, bed_m, left_bank_m, right_bank_m, width_m, method)",
        "select s.id, v.bed, v.left_bank, v.right_bank, v.width, v.method::jsonb",
        "from (values",
    ]
    values = []
    for r in kept:
        method = {
            "heights": "thaiwater station record (left_bank_m, right_bank_m, ground_level_m)",
            "depth_m": r["depth_m"],
            "notes": r["notes"],
            "source": f"gauge_section run, {date.today().isoformat()}",
        }
        if r["width"]:
            method["width"] = {
                "how": "median of 5 transects across OpenStreetMap's digitised water",
                "samples": r["width"]["samples"],
                "spread_m": r["width"]["spread_m"],
                "centreline_m": r["width"]["line_distance_m"],
                "attribution": "(c) OpenStreetMap contributors, ODbL",
            }
        values.append("  ({}, {}::double precision, {}::double precision, {}::double precision, "
                      "{}::double precision, '{}')".format(
                          r["thaiwater_id"], _num(r["bed_m"]), _num(r["left_bank_m"]),
                          _num(r["right_bank_m"]), _num(r["width_m"]),
                          json.dumps(method, ensure_ascii=False).replace("'", "''")))
    out.append(",\n".join(values))
    out += [
        ") as v (thaiwater_id, bed, left_bank, right_bank, width, method)",
        "join public.stations s on s.thaiwater_id = v.thaiwater_id",
        "on conflict (station_id) do update",
        "  set bed_m = excluded.bed_m, left_bank_m = excluded.left_bank_m,",
        "      right_bank_m = excluded.right_bank_m, width_m = excluded.width_m,",
        "      method = excluded.method, updated_at = now();",
        "",
    ]
    return "\n".join(out)
