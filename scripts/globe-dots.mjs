#!/usr/bin/env node
/**
 * Write lib/globe-dots.ts: where the land is, as the dots of the small turning Earth in the map
 * console's head (components/map/OrbitGlobe.tsx).
 *
 * The land is Natural Earth's 1:110m land polygons (public domain, naturalearthdata.com). The
 * sphere is sampled on rings of latitude GLOBE_STEP degrees apart, each ring carrying as many
 * points as fit at that spacing, so the dots are evenly spread and do not crowd at the poles.
 * One bit per point says land or sea; the bits go into the file as base64. Run it again only if
 * the step changes - the land does not.
 *
 *   node scripts/globe-dots.mjs [path/to/ne_110m_land.geojson]
 *
 * Without a path it downloads the file from Natural Earth's own repository.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";
// Must match GLOBE_STEP in lib/globe.ts, which unpacks the same rings.
const STEP = 3;

const land = process.argv[2]
  ? JSON.parse(readFileSync(process.argv[2], "utf8"))
  : await (await fetch(SOURCE)).json();

// Every ring of every polygon; even-odd over all of them handles the lakes cut out of the land.
const rings = [];
for (const feature of land.features) {
  const g = feature.geometry;
  const polygons = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const polygon of polygons) for (const ring of polygon) rings.push(ring);
}

function onLand(lon, lat) {
  let inside = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi)
        inside = !inside;
    }
  }
  return inside;
}

const bits = [];
for (let lat = -90 + STEP / 2; lat < 90; lat += STEP) {
  const n = Math.max(1, Math.round((360 / STEP) * Math.cos((lat * Math.PI) / 180)));
  for (let k = 0; k < n; k++) bits.push(onLand(-180 + (360 * (k + 0.5)) / n, lat) ? 1 : 0);
}

const bytes = new Uint8Array(Math.ceil(bits.length / 8));
bits.forEach((b, i) => {
  if (b) bytes[i >> 3] |= 1 << (i & 7);
});
const count = bits.filter(Boolean).length;
const base64 = Buffer.from(bytes).toString("base64");

writeFileSync(
  join(repo, "lib", "globe-dots.ts"),
  `// Generated by scripts/globe-dots.mjs from Natural Earth's 1:110m land (public domain). Do not edit.
// ${bits.length} points on rings ${STEP} degrees apart, ${count} of them on land; one bit each.
export const LAND_BITS =
  ${JSON.stringify(base64)};
`,
);
console.log(`${count} land dots of ${bits.length} points, ${base64.length} characters`);
